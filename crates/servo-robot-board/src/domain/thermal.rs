//! 温度数据采集辅助函数
//!
//! NTC 温度传感器转换 + MCU 内部温度

use crate::hal::adc;

// ============================================================================
// NTC 温度传感器参数
// ============================================================================

/// NTC 上拉电阻 (Ω)
const NTC_R_PULL: f32 = 100_000.0;
/// NTC 25°C 标称电阻 (Ω)
const NTC_R0: f32 = 100_000.0;
/// NTC B 值 (B25/50)
const NTC_B: f32 = 3950.0;
/// 参考温度 (25°C in Kelvin)
const T0_KELVIN: f32 = 298.15;

// ============================================================================
// NTC 温度转换
// ============================================================================

/// NTC 温度转换 (B3950 100K, 100K 上拉)
///
/// 电路: 3.3V → 100K → ADC → NTC 100K (B3950) → GND
///
/// 公式:
///   R_ntc = R_pull × V_out / (VCC - V_out)
///   1/T = 1/T0 + (1/B) × ln(R_ntc / R0)
pub fn ntc_temp_c(adc_val: u16) -> f32 {
    if adc_val == 0 {
        return -40.0;
    }
    if adc_val >= adc::ADC_MAX as u16 {
        return 125.0;
    }

    let v_ratio = adc_val as f32 / adc::ADC_MAX;
    let r_ntc = NTC_R_PULL * v_ratio / (1.0 - v_ratio);
    let t_kelvin = 1.0 / (1.0 / T0_KELVIN + (1.0 / NTC_B) * libm::logf(r_ntc / NTC_R0));
    t_kelvin - 273.15
}

// ============================================================================
// MCU 内部温度
// ============================================================================

/// MCU 内部温度传感器转换
/// V_sense @ 25°C = 760mV, avg_slope = 2.5mV/°C
pub fn mcu_temp_c(adc_val: u16) -> f32 {
    let v_sense = adc::adc_to_mv(adc_val);
    (v_sense - 760.0) / 2.5 + 25.0
}
